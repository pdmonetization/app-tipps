import fs from 'node:fs';
import path from 'node:path';
import legacyRoutes from '../src/data/legacy-routes.json' with { type: 'json' };

const root = process.cwd();
const dist = path.join(root, 'dist');

if (!fs.existsSync(dist)) {
  process.exit(0);
}

const redirects = Object.entries(legacyRoutes.redirects);

const cleanPath = (value) => decodeURIComponent(value.split(/[?#]/, 1)[0]);

function targetExists(target) {
  const clean = cleanPath(target);
  if (clean === '/') return fs.existsSync(path.join(dist, 'index.html'));

  const relative = clean.replace(/^\/+|\/+$/g, '');
  return fs.existsSync(path.join(dist, relative, 'index.html')) ||
    fs.existsSync(path.join(dist, relative));
}

function sourceOutput(source) {
  const clean = cleanPath(source);
  if (clean === '/') return null;
  const relative = clean.replace(/^\/+|\/+$/g, '');
  if (!relative || relative.includes('*') || relative.includes(':')) return null;
  return path.join(dist, relative, 'index.html');
}

const escapeHtml = (value) => value
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;');

let written = 0;
let skippedMissingTarget = 0;
let skippedExistingPage = 0;

for (const [from, to] of redirects) {
  if (!targetExists(to)) {
    skippedMissingTarget += 1;
    continue;
  }

  const output = sourceOutput(from);
  if (!output) continue;

  // Never replace a real page generated by Astro.
  if (fs.existsSync(output)) {
    skippedExistingPage += 1;
    continue;
  }

  const target = escapeHtml(to);
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="app-tipps-route" content="legacy-redirect-fallback">
  <meta name="robots" content="noindex,follow">
  <meta http-equiv="refresh" content="0;url=${target}">
  <link rel="canonical" href="https://app-tipps.com${target}">
  <title>Page moved | App-Tipps.com</title>
  <script>location.replace(${JSON.stringify(to)});</script>
</head>
<body>
  <p>This page has moved to <a href="${target}">${target}</a>.</p>
</body>
</html>\n`);
  written += 1;
}

console.log(`Legacy redirect fallbacks: ${written} generated, ${skippedMissingTarget} skipped because the destination no longer exists, ${skippedExistingPage} skipped because a real page already exists. Cloudflare Worker supplies the production 301 status.`);
